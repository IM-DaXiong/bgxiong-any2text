// Design-only verification. Run with an existing Playwright installation via NODE_PATH.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');
const root = __dirname;
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BGX_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const receipts = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true, colorScheme: 'light' });
    const errors = [], network = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route(/^https?:/, r => { network.push(r.request().url()); return r.abort(); });
    page.on('dialog', d => d.accept());
    const check = (v, m) => { if (!v) throw Error(m); receipts.push(m); };
    const nav = i => page.locator(`[data-page="${i}"]`).click();
    const action = a => page.locator(`[data-action="${a}"]`).click();
    await page.goto(pathToFileURL(path.join(root, 'any2text-ui.html')).href);
    check(errors.length === 0, 'Initial JavaScript parse and render');
    await page.screenshot({ path: path.join(root, 'any2text-ui-preview.png'), fullPage: true });
    check(await page.locator('[data-action="save"]').evaluate(e => e.getBoundingClientRect().bottom <= 900), 'Save visible in initial desktop viewport');
    await nav(0);
    await page.locator('#model').selectOption({ label: 'Qwen3-ASR · 待安装（示例）' });
    check(await page.locator('[data-action="start"]').isDisabled(), 'Unavailable model blocks submission');
    await page.locator('#model').selectOption({ label: 'Whisper · 本地（示例）' });
    await page.screenshot({ path: path.join(root, 'any2text-ui-import.png'), fullPage: true });
    await action('start');
    await page.screenshot({ path: path.join(root, 'any2text-ui-tasks.png'), fullPage: true });
    await action('pause');
    check((await page.locator('main').innerText()).includes('正在保存当前片段'), 'Pause has pending checkpoint state');
    await page.locator('details.demo summary').click(); await action('settle-pause');
    await action('resume'); await action('cancel'); await action('confirm-cancel');
    check((await page.locator('main').innerText()).includes('正在停止任务'), 'Cancel waits for process termination');
    await page.locator('details.demo summary').click(); await action('settle-cancel');
    check((await page.locator('main').innerText()).includes('153 / 240'), 'Cancelled job preserves committed progress');
    await action('resume'); await page.locator('details.demo summary').click(); await action('interrupt');
    await action('resume'); await page.locator('details.demo summary').click(); await action('fail');
    await action('resume'); await page.locator('details.demo summary').click(); await action('finish');
    check((await page.locator('main').innerText()).includes('结果待取回'), 'Generated results are not yet locally saved');
    await page.locator('#providerStatus').click(); await action('disconnect');
    check(await page.locator('[data-action="cancel-disconnect"]').count() === 0, 'Completed generation cannot be cancelled as a running job');
    await page.screenshot({ path: path.join(root, 'any2text-ui-provider.png'), fullPage: true });
    await action('keep-disconnect');
    check(await page.locator('[data-action="retrieve"]').isDisabled(), 'Disconnected provider cannot retrieve pending results');
    await nav(0); check(await page.locator('[data-action="start"]').isDisabled(), 'Disconnected provider blocks new transcription');
    await nav(3); check(await page.locator('[data-action="generate"]').isDisabled(), 'Disconnected provider blocks generation');
    await nav(4); check(!(await page.locator('[data-action="download"]').isDisabled()), 'Saved sample documents remain exportable offline');
    await action('connect'); await page.locator('#providerStatus').click(); await nav(1); await action('retrieve');
    check((await page.locator('main').innerText()).includes('已保存到本工具'), 'Retrieved results become local documents');
    await action('review');
    await page.locator('#search').fill('声音');
    check(await page.locator('[data-segment]').count() === 3, 'Subtitle search');
    await page.locator('[data-segment="2"]').click();
    check((await page.locator('#currentTime').innerText()) === '00:38:53', 'Source timing seek');
    await page.locator('#edit').fill('校订后的城市声音。');
    await action('write');
    check(await page.locator('[data-action="generate"]').isDisabled(), 'Unsaved corrections block generation');
    await nav(4);
    check(await page.locator('[data-action="download"]').isDisabled(), 'Unsaved corrections block corrected export');
    await page.locator('#exportSource').selectOption('original');
    check(!(await page.locator('[data-action="download"]').isDisabled()), 'Original export remains independent');
    await nav(2); await action('save');
    check((await page.locator('#saveStatus').innerText()).includes('v2'), 'Correction saved to new revision');
    await action('export-subtitle'); await page.locator('#format').selectOption('txt');
    check((await page.locator('.preview').innerText()).includes('校订后的城市声音。'), 'Corrected export uses saved text');
    await page.locator('#exportSource').selectOption('original'); await page.locator('#format').selectOption('txt');
    check(!(await page.locator('.preview').innerText()).includes('校订后的城市声音。'), 'Original text remains unchanged');
    await nav(3); await action('generate'); await action('accept');
    await page.screenshot({ path: path.join(root, 'any2text-ui-write.png'), fullPage: true });
    await action('export-draft');
    check(!(await page.locator('#format option').evaluateAll(xs => xs.map(x => x.value))).includes('srt'), 'Rewritten draft cannot inherit subtitle time');
    await page.screenshot({ path: path.join(root, 'any2text-ui-export.png'), fullPage: true });
    const downloadWait = page.waitForEvent('download'); await action('download');
    const download = await downloadWait;
    check(fs.readFileSync(await download.path(), 'utf8').includes('演示文本'), 'Downloaded file explicitly marked demo');
    await nav(3); await page.locator('#draft').fill('修改后的候选。');
    check(await page.locator('[data-action="export-draft"]').isDisabled(), 'Editing accepted draft invalidates acceptance');
    await action('accept'); await action('source'); await page.locator('#edit').fill('第二次校订。'); await action('save'); await nav(3);
    check(await page.locator('[data-action="accept"]').isDisabled(), 'Changed source invalidates stale draft');
    await page.locator('[data-kind="script"]').click(); await page.locator('#mode').selectOption('creative'); await action('generate');
    check((await page.locator('#draft').inputValue()).includes('新增创作'), 'Creative additions labeled');
    await nav(0); await action('start'); await page.locator('#providerStatus').click(); await action('disconnect'); await action('cancel-disconnect');
    check((await page.locator('main').innerText()).includes('未连接 · 状态待核对'), 'Disconnect after cancellation does not claim terminal success');
    await action('connect'); await page.locator('#providerStatus').click();
    check((await page.locator('main').innerText()).includes('正在停止任务'), 'Reconnection keeps cancellation pending until acknowledgement');
    await page.locator('details.demo summary').click(); await action('settle-cancel');
    check((await page.locator('main').innerText()).includes('已取消'), 'Cancellation becomes terminal only after simulated acknowledgement');
    for (const width of [1440, 1024, 736, 360]) {
      await page.setViewportSize({ width, height: 900 });
      for (let i = 0; i < 5; i++) { await nav(i); check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `No horizontal overflow ${width}px page ${i}`); }
    }
    await page.setViewportSize({ width: 1024, height: 768 }); await nav(2);
    check(await page.locator('[data-action="save"]').evaluate(e => e.getBoundingClientRect().bottom <= 768), 'Save visible at 1024x768');
    await page.locator('#edit').focus(); await page.keyboard.press('Tab');
    check(await page.evaluate(() => document.activeElement.dataset.action === 'save'), 'Keyboard reaches save');
    await page.emulateMedia({ colorScheme: 'dark' });
    await page.screenshot({ path: path.join(root, 'any2text-ui-dark-preview.png'), fullPage: true });
    await page.setViewportSize({ width: 360, height: 800 });
    await page.screenshot({ path: path.join(root, 'any2text-ui-narrow.png'), fullPage: true });
    await page.emulateMedia({ colorScheme: 'light' });
    for (const name of ['any2text-architecture', 'any2text-lifecycle', 'any2text-revisions', 'any2text-flow']) {
      const svg = fs.readFileSync(path.join(root, name + '.svg'), 'utf8');
      const width = Number(svg.match(/width="(\d+)"/)[1]), height = Number(svg.match(/height="(\d+)"/)[1]);
      await page.setViewportSize({ width, height });
      await page.setContent('<html><meta charset="utf-8"><body style="margin:0">' + svg + '</body></html>');
      await page.screenshot({ path: path.join(root, name + '.png') });
    }
    check(errors.length === 0, 'No JavaScript errors'); check(network.length === 0, 'No network requests');
    const result = { status: 'PASS', designRevision: 'v0.4', generatedAt: new Date().toISOString(), checkCount: receipts.length, checks: receipts, scope: 'Design prototype only; no media/model/backend or installer validation' };
    fs.writeFileSync(path.join(root, 'prototype-validation.json'), JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result, null, 2));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
