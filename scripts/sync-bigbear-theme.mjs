import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const host = resolve(root, process.env.BGXIONG_THEME_SOURCE ?? '../bgxiong-ai-story');
const registry = readFileSync(resolve(host, 'ui/src/theme/themeRegistry.ts'), 'utf8');
const stylesheet = readFileSync(resolve(host, 'ui/src/index.css'), 'utf8');
const themes = [...registry.matchAll(/id: "(\w+)", label: "([^"]+)", colorScheme: "(light|dark)"/g)]
  .map(([, id, label, colorScheme]) => ({ id, label, colorScheme }));
if (!themes.length || themes[0].id !== 'dark') throw new Error('Missing BigBear theme registry');

const tokens = ['bg', 'surface', 'surface2', 'input-bg', 'text', 'text2', 'border', 'primary',
  'primary-fg', 'primary-hover', 'accent', 'accent-soft', 'danger'];
const blocks = new Map([...stylesheet.matchAll(/^(:root|\[data-theme="\w+"\])\s*\{([\s\S]*?)^\}/gm)]
  .map(([, selector, body]) => [selector, body]));
const css = themes.map(({ id, colorScheme }) => {
  const selector = id === 'dark' ? ':root' : `[data-theme="${id}"]`;
  const values = tokens.map(token => {
    const pattern = new RegExp(`^\\s*--${token}:\\s*([^;]+);`, 'm');
    const value = blocks.get(selector)?.match(pattern)?.[1] ?? blocks.get(':root')?.match(pattern)?.[1];
    if (!blocks.has(selector) || !value) throw new Error(`Missing BigBear ${id} token ${token}`);
    return `  --${token}: ${value};`;
  });
  return `${selector} {\n  color-scheme: ${colorScheme};\n${values.join('\n')}\n}`;
});

const outputs = {
  'ui/src/bigbear-theme.css': `/* Generated by scripts/sync-bigbear-theme.mjs */\n${css.join('\n\n')}\n`,
  'ui/src/bigbear-theme.json': `${JSON.stringify(themes, null, 2)}\n`,
};
for (const [path, contents] of Object.entries(outputs)) {
  const target = resolve(root, path);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== contents) throw new Error(`${path} differs from BigBear`);
  } else {
    writeFileSync(target, contents);
  }
}
